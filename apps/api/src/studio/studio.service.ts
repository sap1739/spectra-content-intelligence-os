  private async assertLinks(
    scope: Scope,
    input: { contentItemId?: string | null; campaignId?: string | null; brandId?: string | null },
  ) {
    if (input.contentItemId) {
      const item = await this.prisma.client.contentItem.findFirst({
        where: { id: input.contentItemId, ...scope, deletedAt: null },
        select: { id: true },
      });
      if (!item) throw new TenantIsolationError();
    }
    if (input.campaignId) {
      const campaign = await this.prisma.client.campaign.findFirst({
        where: { id: input.campaignId, ...scope, deletedAt: null },
        select: { id: true },
      });
      if (!campaign) throw new TenantIsolationError();
    }
  }

  /** The brand as the plan needs it: name, website and a validated brand kit. */
  async brandContext(scope: Scope, brandId: string | null): Promise<BrandContext | null> {
    if (!brandId) return null;
    const brand = await this.prisma.client.brand.findFirst({
      where: { id: brandId, ...scope, deletedAt: null },
    });
    if (!brand) throw new TenantIsolationError();
    const kit = brandKitSchema.safeParse({
      logoAssetId: brand.logoAssetId,
      palette: brand.palette ?? {},
      typography: brand.typography ?? {},
      tagline: brand.tagline,
      visualStyle: brand.visualStyle,
      offerings: brand.offerings ?? [],
    });
    return { name: brand.name, websiteUrl: brand.websiteUrl, kit: kit.success ? kit.data : null };
  }

  private async planFor(
    scope: Scope,
    design: {
      layout: unknown;
      formatKey: string;
      brandId: string | null;
      values: unknown;
      images: unknown;
    },
  ) {
    const brand = await this.brandContext(scope, design.brandId);
    return this.verifyPlan(
      scope,
      design.layout as TemplateLayout,
      design.formatKey,
      brand,
      design.values as Record<string, string>,
      design.images as Record<string, string>,
      true,
    );
  }

  /**
   * Builds the plan and checks every asset it reads belongs to this workspace
   * and is a raster image (or a font file), within size limits. Returns a
   * loader bound to exactly those checked assets.
   */
  private async verifyPlan(
    scope: Scope,
    layout: TemplateLayout,
    formatKey: string,
    brand: BrandContext | null,
    values: Record<string, string>,
    images: Record<string, string>,
    _forRender: boolean,
  ): Promise<{
    plan: RenderPlan;
    loader: { loadImage(id: string): Promise<Buffer>; loadFont(id: string): Promise<Buffer> };
    versions: Record<string, string>;
  }> {
    if (!getDesignFormat(formatKey))
      throw new UnprocessableEntityException(`Unknown format "${formatKey}".`);
    let plan: RenderPlan;
    try {
      plan = buildRenderPlan({ layout, formatKey, brand, values, images });
    } catch (error) {
      this.invalid(error);
    }
    const fontIds = new Set(
      [
        brand?.kit?.typography.heading?.fontAssetId,
        brand?.kit?.typography.body?.fontAssetId,
      ].filter((id): id is string => Boolean(id)),
    );
    const assets = plan.assetIds.length
      ? await this.prisma.client.mediaAsset.findMany({
          where: { ...scope, id: { in: plan.assetIds } },
          select: { id: true, storageKey: true, mimeType: true, sizeBytes: true, createdAt: true },
        })
      : [];
    const byId = new Map(assets.map((asset) => [asset.id, asset]));
    const versions: Record<string, string> = {};
    for (const id of plan.assetIds) {
      const asset = byId.get(id);
      // Missing and foreign look the same.
      if (!asset)
        throw new UnprocessableEntityException(
          'A referenced image, logo or font is not a media asset in this workspace.',
        );
      assertKeyWithinTenant(asset.storageKey, scope);
      if (fontIds.has(id)) {
        if (!FONT_MIME_TYPES.has(asset.mimeType) || asset.sizeBytes > MAX_FONT_BYTES) {
          throw new UnprocessableEntityException(
            'A brand font must be a TTF or OTF file of at most 5 MB.',
          );
        }
      } else if (!IMAGE_MIME_TYPES.has(asset.mimeType) || asset.sizeBytes > MAX_IMAGE_BYTES) {
        throw new UnprocessableEntityException(
          'Design images and logos must be PNG, JPEG or WebP files of at most 25 MB (SVG is not rendered).',
        );
      }
      versions[id] = `${asset.sizeBytes}:${asset.createdAt.toISOString()}`;
    }
    const cache = new Map<string, Promise<Buffer>>();
    const load = (id: string) => {
      const asset = byId.get(id);
      if (!asset)
        return Promise.reject(
          new UnprocessableEntityException('Asset not available to this render.'),
        );
      let pending = cache.get(id);
      if (!pending) {
        pending = this.storage.getObject(asset.storageKey);
        cache.set(id, pending);
      }
      return pending;
    };
    return { plan, loader: { loadImage: load, loadFont: load }, versions };
  }

  private async renderPage(
    plan: RenderPlan,
    pageIndex: number,
    output: { format: 'png' | 'jpeg'; quality: number; maxWidth?: number | null },
    loader: { loadImage(id: string): Promise<Buffer>; loadFont(id: string): Promise<Buffer> },
  ) {
    try {
      return await this.renderer.renderPage(plan, pageIndex, output, loader);
    } catch (error) {
      if (error instanceof DesignRenderError) throw new UnprocessableEntityException(error.message);
      throw error;
    }
  }
