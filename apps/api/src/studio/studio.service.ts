  listDesigns(tenant: TenantContext, filter: { contentItemId?: string; campaignId?: string } = {}) {
    return this.prisma.client.design.findMany({
      where: {
        ...this.scope(tenant),
        deletedAt: null,
        ...(filter.contentItemId ? { contentItemId: filter.contentItemId } : {}),
        ...(filter.campaignId ? { campaignId: filter.campaignId } : {}),
      },
      orderBy: { updatedAt: 'desc' },
      take: 200,
      include: {
        brand: { select: { id: true, name: true } },
        renders: { select: RENDER_SELECT, orderBy: { createdAt: 'desc' }, take: 12 },
      },
    });
  }

  async getDesign(tenant: TenantContext, id: string) {
    const design = await this.prisma.client.design.findFirst({
      where: { id, ...this.scope(tenant), deletedAt: null },
      include: {
        brand: { select: { id: true, name: true } },
        contentItem: { select: { id: true, title: true, lifecycleState: true } },
        campaign: { select: { id: true, name: true } },
        renders: { select: RENDER_SELECT, orderBy: { createdAt: 'desc' }, take: 50 },
      },
    });
    if (!design) throw new TenantIsolationError();
    return design;
  }

  async createDesign(tenant: TenantContext, principal: Principal, input: CreateDesignInput) {
    const scope = this.scope(tenant);
    let layout: TemplateLayout;
    let templateId: string | null = null;
    let builtInKey: string | null = null;
    let version: number;
    let category: CreateDesignTemplateInput['category'];
    let formats: string[];
    if ('builtInKey' in input.template) {
      const builtIn = getBuiltInTemplate(input.template.builtInKey);
      if (!builtIn) throw new TenantIsolationError();
      ({ layout, version, category, formats } = builtIn);
      builtInKey = builtIn.key;
    } else {
      const template = await this.getTemplate(tenant, input.template.templateId);
      layout = validateTemplateLayout(template.layout);
      ({ version, category, formats } = template);
      templateId = template.id;
    }
    if (!formats.includes(input.formatKey)) {
      throw new UnprocessableEntityException(
        `This template is made for ${formats.join(', ')}; ${input.formatKey} is not one of them.`,
      );
    }
    await this.assertLinks(scope, input);
    const brand = await this.brandContext(scope, input.brandId ?? null);
    await this.verifyPlan(scope, layout, input.formatKey, brand, input.values, input.images, false);

    const design = await this.prisma.client.design.create({
      data: {
        ...scope,
        name: input.name,
        templateId,
        templateBuiltInKey: builtInKey,
        templateVersion: version,
        category,
        layout: layout as unknown as Prisma.InputJsonValue,
        brandId: input.brandId ?? null,
        formatKey: input.formatKey,
        values: input.values as Prisma.InputJsonValue,
        images: input.images as Prisma.InputJsonValue,
        contentItemId: input.contentItemId ?? null,
        campaignId: input.campaignId ?? null,
        createdById: principal.userId,
      },
    });
    await this.audit.record({
      ...scope,
      actorUserId: principal.userId,
      action: 'design.created',
      resourceType: 'Design',
      resourceId: design.id,
      changes: { template: builtInKey ?? templateId, formatKey: input.formatKey },
    });
    return this.getDesign(tenant, design.id);
  }

  async updateDesign(
    tenant: TenantContext,
    principal: Principal,
    id: string,
    input: UpdateDesignInput,
  ) {
    const scope = this.scope(tenant);
    const existing = await this.getDesign(tenant, id);
    if (existing.status === 'ARCHIVED')
      throw new UnprocessableEntityException('This design is archived.');
    const layout = existing.layout as unknown as TemplateLayout;
    const next = {
      brandId: input.brandId !== undefined ? input.brandId : existing.brandId,
      formatKey: input.formatKey ?? existing.formatKey,
      values: input.values ?? (existing.values as Record<string, string>),
      images: input.images ?? (existing.images as Record<string, string>),
    };
    await this.assertLinks(scope, input);
    const brand = await this.brandContext(scope, next.brandId ?? null);
    await this.verifyPlan(scope, layout, next.formatKey, brand, next.values, next.images, false);

    const changesVisuals =
      input.brandId !== undefined ||
      input.formatKey !== undefined ||
      input.values !== undefined ||
      input.images !== undefined;
    const wasApproved = existing.status === 'APPROVED' || existing.status === 'IN_REVIEW';
    await this.prisma.client.design.update({
      where: { id: existing.id },
      data: {
        ...(input.name !== undefined ? { name: input.name } : {}),
        brandId: next.brandId ?? null,
        formatKey: next.formatKey,
        values: next.values as Prisma.InputJsonValue,
        images: next.images as Prisma.InputJsonValue,
        ...(input.contentItemId !== undefined ? { contentItemId: input.contentItemId } : {}),
        ...(input.campaignId !== undefined ? { campaignId: input.campaignId } : {}),
        // An approval covers what was approved. Changing the visuals sends the
        // design back to draft; attaching it to content or a campaign does not.
        ...(changesVisuals && wasApproved
          ? {
              status: 'DRAFT' as const,
              approvedAt: null,
              approvedById: null,
              submittedAt: null,
              reviewNote: 'Edited after review — needs approval again.',
            }
          : {}),
      },
    });
    await this.audit.record({
      ...scope,
      actorUserId: principal.userId,
      action: 'design.updated',
      resourceType: 'Design',
      resourceId: id,
      changes: { visuals: changesVisuals, resetApproval: changesVisuals && wasApproved },
    });
    return this.getDesign(tenant, id);
  }

  async archiveDesign(tenant: TenantContext, principal: Principal, id: string) {
    await this.getDesign(tenant, id);
    await this.prisma.client.design.update({
      where: { id },
      data: { status: 'ARCHIVED', deletedAt: new Date() },
    });
    await this.audit.record({
      ...this.scope(tenant),
      actorUserId: principal.userId,
      action: 'design.archived',
      resourceType: 'Design',
      resourceId: id,
    });
    return { id, archived: true };
  }

